-- 6. Usuários (ÓRFÃ / SEM USO ATUAL): perfil e liberação de acesso de cada
-- conta de login via Supabase Auth. Era usada pela versão anterior em
-- Streamlit, já removida do repositório. O sistema atual (django_app/) usa as
-- tabelas próprias do Django (auth_user, auth_group) para perfil/login, não
-- esta tabela. Mantida aqui só como registro histórico; a linha continua a
-- existir no banco (dados não foram apagados), mas nada mais escreve nela.
--
-- Perfis daquela versão: 'cd' (só lança recebimento, fica pendente),
-- 'compra_venda' (acesso total + aprova/rejeita), 'admin' (acesso total +
-- gestão de usuários) — mesmo desenho de perfis foi recriado no Django como
-- Grupos "CD" / "Compra e Venda" / "Coordenador/Admin".
CREATE TABLE IF NOT EXISTS usuarios (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    apelido TEXT UNIQUE NOT NULL,
    perfil TEXT CHECK (perfil IN ('cd', 'compra_venda', 'admin')),
    ativo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Projetos Supabase recentes vêm com Row Level Security habilitado por padrão em
-- tabelas novas do schema public. Este app não usa RLS em nenhuma tabela (o
-- controle de acesso é feito no Python — ver nota abaixo) — sem esta linha, o
-- próprio login falha ao tentar criar a linha do usuário na primeira vez
-- (erro 42501 "new row violates row-level security policy for table usuarios").
ALTER TABLE usuarios DISABLE ROW LEVEL SECURITY;

-- Nota de segurança: assim como o restante deste app, o controle de acesso é
-- feito no código Python (Streamlit roda no servidor, nunca no navegador do
-- usuário), não por Row Level Security no Postgres. Isso é consistente com
-- como as outras tabelas já funcionam aqui, mas significa que qualquer coisa
-- com a mesma chave do Supabase usada no app.py (SUPABASE_KEY) tem acesso
-- irrestrito a todas as tabelas, inclusive esta. Se um dia esse app ganhar
-- outro cliente (ex: chamadas diretas do navegador), vale revisitar isso e
-- habilitar RLS de verdade.
